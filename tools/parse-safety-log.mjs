/**
 * Builds src/content/safety-log.ts from the two Safety Lessons Log pages on the
 * old site (SftyLssnsLg.asp = volume 2, SftyLssnsLgPrev.asp = volume 1).
 *
 * Both are a single three-column table: Date and Report | Lessons Learned |
 * Actions. The incident's title is bold inside the first cell, which is how the
 * title is separated from the report text here.
 *
 * Run: node tools/parse-safety-log.mjs > src/content/safety-log.ts
 */
import fs from 'node:fs';

const BASE = '/mnt/user-data/uploads/dlgc-mirror/www.dlgc.org.uk/members/safety/';
const SOURCES = [
  { file: 'SftyLssnsLg.asp', volume: 2 },
  { file: 'SftyLssnsLgPrev.asp', volume: 1 },
];

const ENT = [
  [/&nbsp;/gi, ' '], [/&amp;/gi, '&'], [/&lt;/gi, '<'], [/&gt;/gi, '>'],
  [/&quot;/gi, '"'], [/&#39;/g, "'"], [/&rsquo;/gi, '’'], [/&lsquo;/gi, '‘'],
  [/&ldquo;/gi, '“'], [/&rdquo;/gi, '”'], [/&pound;/gi, '£'],
  [/&hellip;/gi, '…'], [/&mdash;/gi, '—'], [/&ndash;/gi, '–'], [/&bull;/gi, '•'],
];
const decode = (s) =>
  ENT.reduce((a, [r, t]) => a.replace(r, t), s).replace(/&#(\d+);/g, (_, d) => String.fromCharCode(+d));

// FrontPage split words across inline tags ("I t was apparent"). Dropping an
// inline tag that sits between two word characters fixes it at source.
const INLINE = 'span|font|strong|b|em|i|u|sup|sub|small|big|a|o:p';
const joinWords = (s) => {
  let out = s;
  for (let i = 0; i < 6; i++) {
    const next = out.replace(new RegExp(`(\\w)(?:<\\/?(?:${INLINE})\\b[^>]*>)+(?=\\w)`, 'gi'), '$1');
    if (next === out) break;
    out = next;
  }
  return out;
};
const text = (s) => decode(joinWords(s).replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

const MONTHS = ['January','February','March','April','May','June','July','August','September','October','November','December'];
const MONTH_RE = new RegExp(`^\\s*(${MONTHS.join('|')}|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sept|Sep|Oct|Nov|Dec)\\.?\\s*(\\d{4})`, 'i');
const MONTH_NUM = {};
MONTHS.forEach((m, i) => { MONTH_NUM[m.toLowerCase()] = i + 1; MONTH_NUM[m.slice(0, 3).toLowerCase()] = i + 1; });
MONTH_NUM.sept = 9;

const entries = [];

for (const { file, volume } of SOURCES) {
  const raw = fs.readFileSync(BASE + file, 'utf8');
  const tables = raw.match(/<table[\s\S]*?<\/table>/gi) ?? [];
  const table = tables.sort((a, b) => b.length - a.length)[0];
  if (!table) continue;

  for (const row of table.match(/<tr[\s\S]*?<\/tr>/gi) ?? []) {
    const cells = row.match(/<t[dh][\s\S]*?<\/t[dh]>/gi) ?? [];
    if (cells.length < 3) continue;

    const first = cells[0];
    const flat = text(first);
    const m = flat.match(MONTH_RE);
    if (!m) continue;                            // header row, or not an entry

    const month = MONTH_NUM[m[1].toLowerCase().replace(/\.$/, '')];
    const year = Number(m[2]);
    if (!month || !year) continue;

    // Title: the first bold run in the cell that is not the date itself.
    let title = '';
    for (const b of first.matchAll(/<(strong|b)\b[^>]*>([\s\S]*?)<\/\1>/gi)) {
      const t = text(b[2]).replace(/[.\s]+$/, '');
      if (!t || t.length < 3) continue;
      if (MONTH_RE.test(t) && t.length < 22) continue;
      title = t.replace(MONTH_RE, '').replace(/^[\s.,:;-]+/, '');
      if (title.length > 90) title = title.slice(0, 90).replace(/\s+\S*$/, '');
      if (title.length >= 3) break;
      title = '';
    }

    let report = flat.replace(MONTH_RE, '').trim();
    if (title) report = report.replace(new RegExp(`^${title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s.,:;-]*`, 'i'), '');
    if (!title) {
      title = report.split(/(?<=[.!?])\s/)[0].split(/\s+/).slice(0, 8).join(' ').replace(/[.\s]+$/, '');
    }

    const lessons = text(cells[1]);
    const actions = text(cells[2]);
    if (!report && !lessons) continue;

    entries.push({
      id: `${year}-${String(month).padStart(2, '0')}-${entries.length}`,
      date: `${year}-${String(month).padStart(2, '0')}`,
      displayDate: `${MONTHS[month - 1]} ${year}`,
      year,
      title: title || 'Safety lesson',
      report,
      lessons,
      actions,
      volume,
    });
  }
}

entries.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

const q = (s) => JSON.stringify(s);
const years = [...new Set(entries.map((e) => e.year))].sort((a, b) => b - a);

const out = `/**
 * SAFETY LESSONS LOG — every entry from the old site's two volumes:
 *   safety/SftyLssnsLg.asp      (volume 2, current)
 *   safety/SftyLssnsLgPrev.asp  (volume 1, earlier)
 *
 * GENERATED by tools/parse-safety-log.mjs. Hand edits are fine; re-running the
 * generator would overwrite them.
 *
 * The point of this log is that members read it. The page shows the most recent
 * five years and loads more on request, with a search box, because a single
 * ${entries.length}-entry page is one nobody scrolls to the bottom of.
 *
 * SAFETY-CRITICAL CONTENT. This is the club's own record of what went wrong and
 * what was learned. Do not paraphrase entries to make them read better.
 */

export type SafetyLesson = {
  id: string;
  /** ISO year-month, for sorting */
  date: string;
  displayDate: string;
  year: number;
  title: string;
  report: string;
  lessons: string;
  actions: string;
  /** 1 = the earlier volume, 2 = the current one */
  volume: 1 | 2;
};

export const safetyLessons: SafetyLesson[] = [
${entries.map((e) => `  { id: ${q(e.id)}, date: ${q(e.date)}, displayDate: ${q(e.displayDate)}, year: ${e.year}, title: ${q(e.title)}, report: ${q(e.report)}, lessons: ${q(e.lessons)}, actions: ${q(e.actions)}, volume: ${e.volume} },`).join('\n')}
];

/** Years present, newest first. */
export const safetyLessonYears: number[] = [${years.join(', ')}];

/** How many years are shown before the member asks for more. */
export const SAFETY_LOG_RECENT_YEARS = 5;

export const safetyLogSource =
  'https://dlgc.org.uk/members/safety/SftyLssnsLg.asp';
`;

process.stdout.write(out);
process.stderr.write(
  `entries: ${entries.length}\nyears: ${years[years.length - 1]}..${years[0]}\n` +
  `vol1: ${entries.filter((e) => e.volume === 1).length}  vol2: ${entries.filter((e) => e.volume === 2).length}\n`
);
